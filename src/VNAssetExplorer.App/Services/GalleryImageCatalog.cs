    internal static void ValidateGameExecutable(string sourceDirectory)
    {
        var path = Path.Combine(sourceDirectory, "WoH.exe");
        if (!File.Exists(path))
            throw new GalleryExecutableException(GalleryExecutableError.Missing, "Gallery extraction requires WoH.exe in the Steam game folder.");
        if ((File.GetAttributes(path) & (FileAttributes.ReparsePoint | FileAttributes.Directory)) != 0)
            throw new GalleryExecutableException(GalleryExecutableError.UnsafePath, "Gallery extraction requires a regular WoH.exe file.");
        using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read);
        var actual = Convert.ToHexString(SHA256.HashData(stream));
        if (!string.Equals(actual, ExecutableSha256, StringComparison.OrdinalIgnoreCase))
            throw new GalleryExecutableException(GalleryExecutableError.UnverifiedVersion, "Gallery extraction is unavailable for this game version.");
    }
